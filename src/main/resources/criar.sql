-- 12 - Avaliações individuais: usuário, tipo de recomendação, item avaliado, nota e data
SELECT
    A.ID_AVALIACAO,
    U.NM_USUARIO,
    CASE
        WHEN A.ID_RECOMENDACAO_CORTE IS NOT NULL THEN 'Corte'
        WHEN A.ID_RECOMENDACAO_COR IS NOT NULL THEN 'Cor'
        WHEN A.ID_RECOMENDACAO_PENTEADO IS NOT NULL THEN 'Penteado'
        WHEN A.ID_RECOMENDACAO_MAQUIAGEM IS NOT NULL THEN 'Maquiagem'
    END AS TIPO_RECOMENDACAO,
    CASE
        WHEN A.ID_RECOMENDACAO_CORTE IS NOT NULL THEN C.NM_CORTE
        WHEN A.ID_RECOMENDACAO_COR IS NOT NULL THEN COR.NM_TONALIDADE
        WHEN A.ID_RECOMENDACAO_PENTEADO IS NOT NULL THEN PEN.NM_PENTEADO
        WHEN A.ID_RECOMENDACAO_MAQUIAGEM IS NOT NULL THEN M.TP_MAQUIAGEM
    END AS ITEM_AVALIADO,
    A.NT_AVALIACAO AS NOTA_USUARIO,
    A.MS_AVALIACAO AS COMENTARIO,
    A.DT_AVALIACAO
FROM T_EM_AVALIACAO A
INNER JOIN T_EM_USUARIO U
    ON A.ID_USUARIO = U.ID_USUARIO
LEFT JOIN T_EM_RECOMENDACAO_CORTE RC
    ON A.ID_RECOMENDACAO_CORTE = RC.ID_RECOMENDACAO_CORTE
LEFT JOIN T_EM_CORTE C
    ON RC.ID_CORTE = C.ID_CORTE
LEFT JOIN T_EM_RECOMENDACAO_COR RCO
    ON A.ID_RECOMENDACAO_COR = RCO.ID_RECOMENDACAO_COR
LEFT JOIN T_EM_COR COR
    ON RCO.ID_COR = COR.ID_COR
LEFT JOIN T_EM_RECOMENDACAO_PENTEADO RP
    ON A.ID_RECOMENDACAO_PENTEADO = RP.ID_RECOMENDACAO_PENTEADO
LEFT JOIN T_EM_PENTEADO PEN
    ON RP.ID_PENTEADO = PEN.ID_PENTEADO
LEFT JOIN T_EM_RECOMENDACAO_MAQUIAGEM RM
    ON A.ID_RECOMENDACAO_MAQUIAGEM = RM.ID_RECOMENDACAO_MAQUIAGEM
LEFT JOIN T_EM_MAQUIAGEM M
    ON RM.ID_MAQUIAGEM = M.ID_MAQUIAGEM
ORDER BY A.DT_AVALIACAO DESC, U.NM_USUARIO;

-- 13 - Recomendações cuja média de avaliações dos usuários está acima da média geral
WITH AVALIACOES AS
(
    SELECT
        'Corte' AS TIPO_RECOMENDACAO,
        RC.ID_RECOMENDACAO_CORTE AS ID_RECOMENDACAO,
        C.NM_CORTE AS ITEM_RECOMENDADO,
        A.NT_AVALIACAO AS NOTA
    FROM T_EM_AVALIACAO A
    INNER JOIN T_EM_RECOMENDACAO_CORTE RC
        ON A.ID_RECOMENDACAO_CORTE = RC.ID_RECOMENDACAO_CORTE
    INNER JOIN T_EM_CORTE C
        ON RC.ID_CORTE = C.ID_CORTE

    UNION ALL

    SELECT
        'Cor',
        RCO.ID_RECOMENDACAO_COR,
        COR.NM_TONALIDADE,
        A.NT_AVALIACAO
    FROM T_EM_AVALIACAO A
    INNER JOIN T_EM_RECOMENDACAO_COR RCO
        ON A.ID_RECOMENDACAO_COR = RCO.ID_RECOMENDACAO_COR
    INNER JOIN T_EM_COR COR
        ON RCO.ID_COR = COR.ID_COR

    UNION ALL

    SELECT
        'Penteado',
        RP.ID_RECOMENDACAO_PENTEADO,
        PEN.NM_PENTEADO,
        A.NT_AVALIACAO
    FROM T_EM_AVALIACAO A
    INNER JOIN T_EM_RECOMENDACAO_PENTEADO RP
        ON A.ID_RECOMENDACAO_PENTEADO = RP.ID_RECOMENDACAO_PENTEADO
    INNER JOIN T_EM_PENTEADO PEN
        ON RP.ID_PENTEADO = PEN.ID_PENTEADO

    UNION ALL

    SELECT
        'Maquiagem',
        RM.ID_RECOMENDACAO_MAQUIAGEM,
        M.TP_MAQUIAGEM,
        A.NT_AVALIACAO
    FROM T_EM_AVALIACAO A
    INNER JOIN T_EM_RECOMENDACAO_MAQUIAGEM RM
        ON A.ID_RECOMENDACAO_MAQUIAGEM = RM.ID_RECOMENDACAO_MAQUIAGEM
    INNER JOIN T_EM_MAQUIAGEM M
        ON RM.ID_MAQUIAGEM = M.ID_MAQUIAGEM
),
MEDIA_RECOMENDACOES AS
(
    SELECT
        TIPO_RECOMENDACAO,
        ID_RECOMENDACAO,
        ITEM_RECOMENDADO,
        COUNT(*) AS QTD_AVALIACOES,
        ROUND(AVG(NOTA), 2) AS MEDIA_NOTA
    FROM AVALIACOES
    GROUP BY TIPO_RECOMENDACAO, ID_RECOMENDACAO, ITEM_RECOMENDADO
)
SELECT
    TIPO_RECOMENDACAO,
    ID_RECOMENDACAO,
    ITEM_RECOMENDADO,
    QTD_AVALIACOES,
    MEDIA_NOTA
FROM MEDIA_RECOMENDACOES
WHERE MEDIA_NOTA > (
    SELECT AVG(NT_AVALIACAO)
    FROM T_EM_AVALIACAO
)
ORDER BY MEDIA_NOTA DESC, TIPO_RECOMENDACAO;

