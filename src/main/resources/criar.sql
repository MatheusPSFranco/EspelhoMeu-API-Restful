    ON PM.ID_PERFIL_MAQUIAGEM = CM.ID_PERFIL_MAQUIAGEM
INNER JOIN T_EM_RECOMENDACAO_MAQUIAGEM RM
    ON CM.ID_CONSULTORIA_MAQUIAGEM = RM.ID_CONSULTORIA_MAQUIAGEM
INNER JOIN T_EM_MAQUIAGEM M
    ON RM.ID_MAQUIAGEM = M.ID_MAQUIAGEM
WHERE U.ID_USUARIO = 1
ORDER BY RM.DT_MAQUIAGEM DESC;

-- 6 - Quantidade de favoritos de cada usuário, incluindo quem não possui favoritos (LEFT JOIN)
SELECT
    U.ID_USUARIO,
    U.NM_USUARIO,
    COUNT(F.ID_FAVORITO) AS QTD_FAVORITOS
FROM T_EM_USUARIO U
LEFT JOIN T_EM_FAVORITOS F
    ON U.ID_USUARIO = F.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NM_USUARIO
ORDER BY QTD_FAVORITOS DESC, U.NM_USUARIO;

-- 7 - Estatísticas das avaliações externas dos produtos capilares por faixa de preço
SELECT
    P.FX_PRECO,
    COUNT(P.ID_PRODUTO) AS QTD_PRODUTOS,
    ROUND(AVG(P.AV_PRODUTO), 2) AS MEDIA_AVALIACAO_EXTERNA,
    MAX(P.AV_PRODUTO) AS MAIOR_AVALIACAO,
    MIN(P.AV_PRODUTO) AS MENOR_AVALIACAO
FROM T_EM_PRODUTO P
WHERE P.AV_PRODUTO IS NOT NULL
GROUP BY P.FX_PRECO
HAVING AVG(P.AV_PRODUTO) >= 4.0
ORDER BY MEDIA_AVALIACAO_EXTERNA DESC;

-- 8 - Produtos de maquiagem com nota externa acima da média geral (SUBSELECT)
SELECT
    M.ID_MAQUIAGEM,
    M.TP_MAQUIAGEM,
    M.MC_MAQUIAGEM,
    M.LN_MAQUIAGEM,
    M.AV_MAQUIAGEM AS MEDIA_AVALIACAO_EXTERNA
FROM T_EM_MAQUIAGEM M
WHERE M.AV_MAQUIAGEM > (
    SELECT AVG(M2.AV_MAQUIAGEM)
    FROM T_EM_MAQUIAGEM M2
    WHERE M2.AV_MAQUIAGEM IS NOT NULL
)
ORDER BY M.AV_MAQUIAGEM DESC;

