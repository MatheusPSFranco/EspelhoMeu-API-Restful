--06- Quantidade de favoritos de cada usuario (LEFT JOIN)

SELECT
    U.ID_USUARIO,
    U.NM_USUARIO,
    COUNT(F.ID_FAVORITO) AS QTD_FAVORITOS
FROM T_EM_USUARIO U
LEFT JOIN T_EM_FAVORITOS F
    ON U.ID_USUARIO = F.ID_USUARIO
GROUP BY U.ID_USUARIO, U.NM_USUARIO
ORDER BY QTD_FAVORITOS DESC, U.NM_USUARIO;

--07- Estatisticas das avaliacoes dos produtos por faixa de preco

SELECT
    P.FX_PRECO,
    COUNT(P.ID_PRODUTO) AS QTD_PRODUTOS,
    SUM(P.AV_PRODUTO) AS SOMA_AVALIACOES,
    ROUND(AVG(P.AV_PRODUTO), 2) AS MEDIA_AVALIACAO,
    MAX(P.AV_PRODUTO) AS MAIOR_AVALIACAO,
    MIN(P.AV_PRODUTO) AS MENOR_AVALIACAO
FROM T_EM_PRODUTO P
WHERE P.AV_PRODUTO IS NOT NULL
GROUP BY P.FX_PRECO
HAVING AVG(P.AV_PRODUTO) >= 4.0
ORDER BY MEDIA_AVALIACAO DESC;

--08- Maquiagens com avaliacao acima da media geral (SUBSELECT)

SELECT
    M.ID_MAQUIAGEM,
    M.TP_MAQUIAGEM,
    M.MC_MAQUIAGEM,
    M.LN_MAQUIAGEM,
    M.AV_MAQUIAGEM
FROM T_EM_MAQUIAGEM M
WHERE M.AV_MAQUIAGEM > (
    SELECT AVG(M2.AV_MAQUIAGEM)
    FROM T_EM_MAQUIAGEM M2
)
ORDER BY M.AV_MAQUIAGEM DESC;

