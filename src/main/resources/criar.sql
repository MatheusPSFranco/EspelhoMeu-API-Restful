--01- Cortes favoritos de um usuario especifico

SELECT
    U.ID_USUARIO,
    U.NM_USUARIO,
    C.ID_CORTE,
    C.NM_CORTE,
    F.DT_FAVORITO
FROM T_EM_FAVORITOS F
INNER JOIN T_EM_USUARIO U
    ON F.ID_USUARIO = U.ID_USUARIO
INNER JOIN T_EM_CORTE C
    ON F.ID_CORTE = C.ID_CORTE
WHERE F.ID_USUARIO = 1
    AND F.ID_CORTE IS NOT NULL
ORDER BY F.DT_FAVORITO DESC;

--02- Cortes q foram recomendados para cada usuario

SELECT
    U.NM_USUARIO,
    PC.CP_ATUAL,
    PC.CP_DESEJADO,
    C.NM_CORTE,
    RC.JT_CORTE,
    RC.DT_CORTE
FROM T_EM_USUARIO U
INNER JOIN T_EM_PERFIL_CABELO PC
    ON U.ID_USUARIO = PC.ID_USUARIO
INNER JOIN T_EM_CONSULTORIA_CAPILAR CC
    ON PC.ID_PERFIL_CABELO = CC.ID_PERFIL_CABELO
INNER JOIN T_EM_RECOMENDACAO_CORTE RC
    ON CC.ID_CONSULTORIA = RC.ID_CONSULTORIA
INNER JOIN T_EM_CORTE C
    ON RC.ID_CORTE = C.ID_CORTE
ORDER BY RC.DT_CORTE DESC;

--03- Produtos associados a uma recomendação corte

SELECT
    RC.ID_RECOMENDACAO_CORTE,
    C.NM_CORTE,
    P.TP_PRODUTO,
    P.MC_PRODUTO,
    P.FX_PRECO,
    TRUNC(SYSDATE) - TRUNC(RC.DT_CORTE) AS DIAS_DESDE_RECOMENDACAO
FROM T_EM_RECOMENDACAO_CORTE RC
INNER JOIN T_EM_CORTE C
    ON RC.ID_CORTE = C.ID_CORTE
INNER JOIN T_EM_REC_COT_PRO RCP
    ON RC.ID_RECOMENDACAO_CORTE = RCP.ID_RECOMENDACAO_CORTE
INNER JOIN T_EM_PRODUTO P
    ON RCP.ID_PRODUTO = P.ID_PRODUTO
WHERE RC.ID_RECOMENDACAO_CORTE = 1
ORDER BY P.TP_PRODUTO;

--04- Todos os usuarios, incluindo aqueles sem perfil capilar (RIGHT JOIN)

SELECT
    U.ID_USUARIO,
    U.NM_USUARIO,
    U.EM_USUARIO,
    PC.ID_PERFIL_CABELO,
    PC.CP_ATUAL,
    PC.CP_DESEJADO
FROM T_EM_PERFIL_CABELO PC
RIGHT JOIN T_EM_USUARIO U
    ON PC.ID_USUARIO = U.ID_USUARIO
ORDER BY U.NM_USUARIO;

--05- Maquiagem recomendada para um usuario especifico

SELECT
    U.NM_USUARIO,
    M.TP_MAQUIAGEM,
    M.CR_MAQUIAGEM,
    M.FX_PRECO,
    M.LN_MAQUIAGEM,
    RM.JT_MAQUIAGEM,
